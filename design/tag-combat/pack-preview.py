"""Bundle sprite metadata for a review page that also opens from file://."""
import json
from pathlib import Path
from PIL import Image

here = Path(__file__).resolve().parent
assets = here.parents[1] / "game/art/tag-combat"
units = json.loads((assets / "units.json").read_text(encoding="utf-8"))
effects = json.loads((assets / "fx.json").read_text(encoding="utf-8"))
alpha = Image.open(assets / units["gear"]["file"]).getchannel("A")
w, h = units["gear"]["cell"]
bounds = []
for row in range(3):
    left, top, right, bottom = alpha.crop((0, row*h, w, (row+1)*h)).getbbox()
    bounds.append([left, top, right-left, bottom-top])
data = {
    "muzzles": [[frame["muzzle"] for frame in row["frames"]] for row in units["rows"]],
    "fx": effects["clips"],
    "gearBounds": bounds,
}
(here / "atlas-data.js").write_text(
    "/* Generated by pack-preview.py */\nconst ATLAS = " +
    json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8"
)
